const std = @import("std");
const p = @import("protocol.zig");
const win = @import("win32.zig");
const t = @import("model_types.zig");
const state = @import("model_state.zig");
const capture = @import("model_capture.zig");
const read = capture.read;
const obs = @import("observation.zig");
extern fn entities_observed_generation(usize) u32;
pub fn record(op: *const t.Lease, s: *const t.Scope, actor: usize, controller: usize) void {
    if (!state.live(op) or state.clonewars_model_projection_enabled == 0) return;
    var r = std.mem.zeroes(t.Projection);
    r.id = obs.increment(&state.clonewars_model_projection_count);
    r.epoch = s.epoch;
    r.sequence = s.sequence;
    r.ordinal = s.ordinal;
    r.slot = s.request.slot;
    r.generation = s.request.generation;
    r.thread = win.GetCurrentThreadId();
    r.clock = read(u32, 0xfb4b6c);
    obs.timestamp(&r.qpc[0], &r.qpc[1]);
    r.actor_local = @truncate(actor);
    r.controller_local = @truncate(controller);
    r.provider_local = @truncate(s.provider);
    r.native_frame = s.native_frame;
    r.source_local_mode = s.local_mode;
    r.cmp_seen = s.cmp_seen;
    r.mov_seen = s.mov_seen;
    r.cmp_native_flags = s.cmp_native_flags;
    r.cmp_effective_flags = s.cmp_effective_flags;
    r.mov_native_mode = s.mov_native_mode;
    r.effective_mode = s.request.input_mode;
    r.request = s.request;
    r.raw_source_context = s.raw_source_context;
    r.canonicalized_fields = s.canonicalized_fields;
    r.control_25 = read(u8, controller + 0x25);
    r.heading_26 = read(u16, controller + 0x26);
    r.magnitude = read(u32, controller + 0x28);
    r.direction = read([2]u32, controller + 0x2c);
    r.c7c = read(u32, actor + 0xc7c);
    const base = read(usize, actor + 0xc08);
    r.base_valid = @intFromBool(capture.valid(base, 0x228));
    r.base_heading = if (r.base_valid != 0) read(u32, base + 0x224) else 0;
    r.actor_heading = read(u16, actor + 0x6c);
    r.action = read(u16, actor + 0x2f4);
    r.life_54 = read(u8, actor + 0x54);
    if (!state.live(op) or state.scope != s) return;
    obs.publish(&state.clonewars_model_projection_records[(r.id -% 1) % 2048], &r);
}
pub fn outcome(op: *const t.Lease) void {
    if (!state.live(op)) return;
    const correction = &state.clonewars_model_input_first_correction;
    const f = state.journal.frame.?;
    if (correction[0] == 0 or state.clonewars_model_input_first_outcome.committed != 0 or correction[0] != f.epoch or correction[1] != f.sequence) return;
    var r = std.mem.zeroes(t.Outcome);
    r.hero_role = std.math.maxInt(u32);
    r.sequence = f.sequence;
    r.ordinal = correction[2];
    r.slot = correction[3];
    r.generation = correction[4];
    r.actor_local = @truncate(state.first_actor);
    r.controller_local = @truncate(state.first_controller);
    r.clock = read(u32, 0xfb4b6c);
    obs.timestamp(&r.qpc[0], &r.qpc[1]);
    const actor = state.first_actor;
    const controller = state.first_controller;
    if (!capture.valid(actor, 0x1440) or !capture.valid(controller, 0x60)) r.reason = 1 else if (read(u32, actor + 0x50) & 3 != 3 or state.first_generation == 0 or entities_observed_generation(actor) != state.first_generation) r.reason = 2 else if (!state.live(op)) return else if (read(usize, actor + 0x6cc) != controller) r.reason = 3 else {
        r.valid = 1;
        r.actor_heading = read(u16, actor + 0x6c);
        r.controller_heading = read(u16, controller + 0x26);
        r.magnitude = read(u32, controller + 0x28);
        r.direction = read([2]u32, controller + 0x2c);
        r.previous_heading = read(u16, controller + 0x5a);
        r.previous_magnitude = read(u32, controller + 0x38);
        r.last_heading = read(u16, controller + 0x5e);
        r.last_magnitude = read(u32, controller + 0x34);
        r.action = read(u16, actor + 0x2f4);
        r.substate = read(u8, actor + 0x2fa);
        r.clip = read(u16, actor + 0x2e8);
        r.timer = read(u32, actor + 0x2a0);
        r.life_54 = read(u8, actor + 0x54);
        r.flags_50 = read(u32, actor + 0x50);
        r.hero_role = if (actor == capture.hero(0)) 0 else if (actor == capture.hero(1)) 1 else std.math.maxInt(u32);
        r.position = read([3]f32, actor + 0x24);
    }
    if (!state.live(op)) return;
    state.clonewars_model_input_first_outcome = r;
    @atomicStore(u32, &state.clonewars_model_input_first_outcome.committed, f.epoch, .seq_cst);
}
