const std = @import("std");
const s = @import("lan_state.zig");
const p = @import("protocol.zig");
const check = std.debug.assert;
pub const panic = @import("safety.zig").panic;
var invalidations: u32 = 0;
var invalidated_to: u32 = 0;
var previous_session: u32 = 0;
fn invalidate(next: u32, context: usize) callconv(.c) void {
    check(context == 17);
    invalidations += 1;
    invalidated_to = next;
    previous_session = s.lan_session_serial();
}
fn ready(epoch: u32, level: i32, phase: u32, serial: u32) p.SyncWorldReady {
    return .{ .epoch = epoch, .level = level, .root_phase = phase, .completed_serial = serial, .collider_count = 0, .collider_roster = 0 };
}
fn input(epoch: u32, level: i32, phase: u32) p.SyncPreloadInput {
    var value = std.mem.zeroes(p.SyncPreloadInput);
    value.epoch = epoch;
    value.level = level;
    value.serial = 1;
    value.root_phase = phase;
    value.delta = 0.1;
    value.engine_delta = 0.1;
    return value;
}
fn receiptValue(calls: u32, phase: u32) p.SyncPreloadReceipt {
    var value = std.mem.zeroes(p.SyncPreloadReceipt);
    value.serial = 1;
    value.world_calls = calls;
    value.end_phase = phase;
    return value;
}
pub fn main() void {
    check(s.lan_set_session_invalidator(invalidate, 17) == 1);
    check(s.lan_set_session_invalidator(invalidate, 17) == 1);
    check(s.lan_set_session_invalidator(invalidate, 18) == 0);
    s.publishSession(1);
    s.generation = 1;
    s.host_role = 1;
    s.lan_publish_transition(1, 6, 1);
    check(s.local_state.epoch == 1 and s.local_state.level == 6 and s.local_state.native_entry == 1);
    s.lan_publish_transition(1, 6, 0);
    check(s.local_state.native_entry == 1);
    s.lan_publish_transition(2, 7, 0);
    check(s.local_state.epoch == 2 and s.local_state.level == 7 and s.local_state.native_entry == 0);
    s.lan_publish_transition(2, 7, 1);
    check(s.local_state.native_entry == 0);
    s.lan_publish_transition(3, 8, 3);
    check(s.local_state.epoch == 2 and s.local_state.level == 7);
    var remote: s.Peer = .{ .epoch = 2, .level = 7 };
    check(s.sessionPeer(1, &remote));
    var accepted = s.lan_remote_transition();
    check(accepted.epoch == 2 and accepted.level == 7 and accepted.native_entry == 0);
    remote.epoch = 3;
    remote.level = 8;
    remote.native_entry = 1;
    check(s.sessionPeer(1, &remote));
    accepted = s.lan_remote_transition();
    check(accepted.epoch == 3 and accepted.level == 8 and accepted.native_entry == 1);
    remote.native_entry = 3;
    check(!s.sessionPeer(1, &remote));
    remote.native_entry = 0;
    check(!s.sessionPeer(2, &remote));
    accepted = s.lan_remote_transition();
    check(accepted.epoch == 3 and accepted.level == 8 and accepted.native_entry == 1);
    s.lan_publish_transition(4, 8, p.SYNC_TRANSITION_NATIVE_CYCLE);
    check(s.local_state.epoch == 4 and s.local_state.native_entry == p.SYNC_TRANSITION_NATIVE_CYCLE);
    remote.epoch = 4;
    remote.level = 8;
    remote.native_entry = p.SYNC_TRANSITION_NATIVE_CYCLE;
    check(s.sessionPeer(1, &remote));
    accepted = s.lan_remote_transition();
    check(accepted.epoch == 4 and accepted.level == 8 and accepted.native_entry == p.SYNC_TRANSITION_NATIVE_CYCLE);
    s.lan_publish_transition(4, 12, 1);
    remote = .{ .epoch = 3, .level = 8, .ready = 1 };
    check(s.sessionPeer(1, &remote));
    check(s.lan_peer_ready() == 0);
    remote.epoch = 4;
    remote.level = 12;
    remote.ready = 0;
    check(s.sessionPeer(1, &remote));
    check(s.lan_peer_ready() == 0);
    remote.ready = 1;
    check(s.sessionPeer(1, &remote));
    check(s.lan_peer_ready() == 1);
    remote.ack = 17;
    check(s.sessionPeer(1, &remote));
    check(s.lan_peer_ack() == 17);
    remote.level = 11;
    check(s.sessionPeer(1, &remote));
    check(s.lan_peer_ack() == 0);
    remote.level = 12;
    remote.ready = 0;
    check(s.sessionPeer(1, &remote));
    check(s.lan_peer_ready() == 0);
    remote.epoch = 5;
    remote.level = 13;
    remote.ready = 1;
    check(s.sessionPeer(1, &remote));
    check(s.lan_peer_ready() == 0);
    s.status = 3;
    s.host_role = 1;
    s.lan_publish_transition(6, 7, 0);
    var source = input(6, 7, 0xd);
    source.rng_game = 0xffffffff;
    source.rng_engine = 0xffffffff;
    var world = ready(6, 7, 0xd, 0);
    var observed_world = ready(0, -1, 0, 0);
    check(s.lan_publish_preload(&source) == 0);
    check(s.lan_publish_world_ready(&world) == 1);
    check(s.lan_publish_preload(&source) == 0);
    s.peer_state = .{ .epoch = 6, .level = 7, .world_ready = world };
    check(s.lan_remote_world_ready(6, 7, &observed_world) == 1 and @import("validation.zig").equal(&world, &observed_world));
    check(s.lan_publish_preload(&source) == 1);
    var receipt = receiptValue(2, 0xe);
    var observed = std.mem.zeroes(p.SyncPreloadReceipt);
    check(s.lan_publish_preload_receipt(6, 7, &receipt) == 1);
    check(s.lan_publish_preload_seal(6, 7, 1) == 0);
    s.peer_state = .{ .epoch = 6, .level = 7, .preload_receipt = receipt, .world_ready = world };
    check(s.lan_remote_preload_receipt(6, 7, &observed) == 1);
    check(observed.serial == 1 and observed.world_calls == 2);
    check(s.lan_publish_preload_seal(6, 7, 1) == 0);
    world.root_phase = 0xe;
    world.completed_serial = 1;
    check(s.lan_publish_world_ready(&world) == 1);
    check(s.lan_publish_preload_seal(6, 7, 1) == 0);
    s.peer_state.world_ready = world;
    check(s.lan_publish_preload_seal(6, 7, 1) == 1);
    check(s.local_state.preload_seal == 1);
    s.lan_publish_transition(7, 7, 0);
    check(s.local_state.preload.epoch == 0 and s.local_state.preload_receipt.serial == 0 and s.local_state.preload_seal == 0);
    check(s.local_state.world_ready.epoch == 0 and s.local_state.world_ready.level == -1);
    check(s.lan_publish_preload_receipt(6, 7, &receipt) == 0);
    check(s.lan_remote_preload_receipt(7, 7, &observed) == 0);
    s.host_role = 0;
    s.peer_state = .{ .epoch = 7, .level = 7, .preload = source, .preload_receipt = receipt, .preload_seal = 1 };
    s.peer_state.preload.epoch = 7;
    world = ready(7, 7, 0xd, 0);
    check(s.lan_publish_world_ready(&world) == 1);
    check(s.lan_receive_preload(7, 7, &source) == 1);
    check(s.lan_publish_preload(&source) == 0);
    check(s.lan_publish_preload_receipt(7, 7, &receipt) == 1);
    check(s.lan_remote_preload_seal(7, 7) == 1);
    check(s.lan_remote_preload_seal(6, 7) == 0);
    s.lan_publish_level(8);
    check(s.local_state.preload_receipt.serial == 0 and s.local_state.preload_seal == 0 and s.local_state.world_ready.epoch == 0);
    world = ready(7, 8, 0xd, 0);
    check(s.lan_publish_world_ready(&world) == 1);
    s.lan_invalidate_world_ready();
    check(s.local_state.world_ready.epoch == 0 and s.local_state.world_ready.level == -1);
    world.epoch = 6;
    check(s.lan_publish_world_ready(&world) == 0);
    world.epoch = 7;
    world.level = 7;
    check(s.lan_publish_world_ready(&world) == 0);
    s.host_role = 1;
    for (0xd..0xf) |phase_value| {
        const phase: u32 = @intCast(phase_value);
        const epoch = 20 + phase;
        s.lan_publish_transition(epoch, 7, 0);
        source = input(epoch, 7, phase);
        world = ready(epoch, 7, phase, 0);
        s.peer_state = .{ .epoch = epoch, .level = 7, .world_ready = world };
        check(s.lan_publish_world_ready(&world) == 1 and s.lan_publish_preload(&source) == 1);
        receipt = receiptValue(1, phase);
        check(s.lan_publish_preload_receipt(epoch, 7, &receipt) == 1);
        world.completed_serial = 1;
        check(s.lan_publish_world_ready(&world) == 1);
        s.peer_state.world_ready = world;
        check(s.lan_publish_preload_seal(epoch, 7, 1) == 0);
        s.peer_state.preload_receipt = receipt;
        s.peer_state.world_ready.root_phase = if (phase == 0xd) 0xe else 0xd;
        check(s.lan_publish_preload_seal(epoch, 7, 1) == 0);
        s.peer_state.world_ready = world;
        s.peer_state.preload_receipt.world_calls += 1;
        check(s.lan_publish_preload_seal(epoch, 7, 1) == 0);
        s.peer_state.preload_receipt = receipt;
        s.peer_state.preload_receipt.end_phase = if (phase == 0xd) 0xe else 0xd;
        check(s.lan_publish_preload_seal(epoch, 7, 1) == 0);
        s.peer_state.preload_receipt = receipt;
        check(s.local_state.preload_seal == 0);
        check(s.lan_publish_preload_seal(epoch, 7, 1) == 1 and s.local_state.preload_seal == 1);
    }
    const allocator = std.heap.page_allocator;
    const frame = allocator.create(p.SyncFrame) catch unreachable;
    defer allocator.destroy(frame);
    frame.* = std.mem.zeroes(p.SyncFrame);
    frame.epoch = s.local_state.epoch;
    frame.level = 7;
    frame.sequence = 1;
    frame.delta = 0.016;
    s.clearFrames();
    for (0..p.SYNC_QUEUE_SIZE) |_| check(s.lan_send_frame(frame) == 1);
    check(s.lan_send_frame(frame) == 0);
    check(s.takeFrame(1, frame));
    check(s.lan_send_frame(frame) == 1);
    s.clearFrames();
    frame.epoch = s.local_state.epoch - 1;
    check(s.sessionInbound(1, frame) == 1);
    frame.epoch += 1;
    check(s.sessionInbound(1, frame) == 1);
    check(s.lan_receive_frame(frame) == 1 and frame.epoch == s.local_state.epoch);
    check(s.lan_receive_frame(frame) == 0);
    check(s.sessionInbound(2, frame) == 0);
    var own: s.Peer = undefined;
    s.lan_publish_ack(19);
    check(s.publicationSnapshot(1, &own, false, s.local_state.epoch, 18) == 1);
    check(s.publicationSnapshot(1, &own, false, s.local_state.epoch, 19) == 0);
    s.lan_stop();
    check(invalidations == 1 and invalidated_to == 2 and previous_session == 1 and s.lan_session_serial() == 2);
    check(!s.active(1) and s.active(2));
    s.generation = 0xfffffffd;
    s.publishSession(s.generation);
    s.lan_stop();
    check(s.lan_session_serial() == 0xfffffffe and s.active(0xfffffffe));
    s.lan_stop();
    check(invalidations == 3 and invalidated_to == 0 and previous_session == 0xfffffffe);
    check(s.lan_session_serial() == 0 and !s.active(0xfffffffe) and s.lan_error() == 534);
    s.lan_stop();
    check(invalidations == 3);
}
