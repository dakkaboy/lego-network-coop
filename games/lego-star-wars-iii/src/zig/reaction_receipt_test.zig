const std = @import("std");
const p = @import("protocol.zig");
const r = @import("reaction.zig");
const check = @import("native_test_support.zig").check;
var frame = std.mem.zeroes(p.SyncFrame);
fn complete(client: *r.Journal, begin: u32, slot: u32, generation: u32, source: u32, hit: *const p.SyncReactionHitOutcome) c_int {
    return r.reaction_journal_complete_no_clip(client, begin, slot, generation, source, hit);
}
pub fn main() void {
    var clip = std.mem.zeroes(p.SyncReactionChoice);
    clip.slot = 3;
    clip.generation = 8;
    clip.character = 321;
    clip.old_action = 20;
    clip.kind = p.SYNC_REACTION_CLIP;
    clip.payload.clip.selection.clip = -1;
    clip.payload.clip.source_id = 77;
    clip.payload.clip.hit = .{ .completed = 1, .health_before = 4, .health_after = 3, .life_before = 3, .life_after = 3, .action_before = 0, .action_after = 0, .timer_before = 0, .timer_after = 0 };
    const actual = clip.payload.clip.hit;
    var draw = clip;
    draw.kind = p.SYNC_REACTION_DAMAGE_DRAW;
    draw.payload.clip.selection.damage_draw = 100;
    draw.payload.clip.hit = std.mem.zeroes(p.SyncReactionHitOutcome);
    var host: r.Journal = undefined;
    var client: r.Journal = undefined;
    r.reaction_journal_begin(&host, &frame, 1);
    check(@src(), r.reaction_journal_record(&host, &draw) == 1 and r.reaction_journal_record(&host, &clip) == 1);
    r.reaction_journal_begin(&client, &frame, 0);
    check(@src(), complete(&client, 0, 3, 8, 77, &actual) == 0 and client.cursor == 0 and r.reaction_journal_finish(&client) == 0);
    client.cursor = 1;
    check(@src(), complete(&client, 0, 4, 8, 77, &actual) == 0 and complete(&client, 0, 3, 9, 77, &actual) == 0 and complete(&client, 0, 3, 8, 78, &actual) == 0 and client.cursor == 1);
    check(@src(), complete(&client, 0, 3, 8, 77, &actual) == 1 and client.cursor == 2 and r.reaction_journal_finish(&client) == 1);
    check(@src(), frame.reactions[client.cursor - 1].payload.clip.source_id == 77 and frame.reactions[client.cursor - 1].payload.clip.selection.clip == -1);
    check(@src(), r.reaction_journal_record(&host, &clip) == 1 and complete(&client, 0, 3, 8, 77, &actual) == 0 and client.cursor == 2);
    check(@src(), complete(&client, 2, 3, 8, 77, &actual) == 1 and client.cursor == 3);
    r.reaction_journal_begin(&host, &frame, 1);
    check(@src(), r.reaction_journal_record(&host, &clip) == 1 and r.reaction_journal_record(&host, &clip) == 1);
    r.reaction_journal_begin(&client, &frame, 0);
    var selected: u32 = 12;
    check(@src(), r.reaction_journal_apply(&client, r.reaction_journal_peek(&client), 1, 20, 77, 1, &selected) == 1 and selected == 0xffffffff);
    check(@src(), complete(&client, 0, 3, 8, 77, &actual) == 0 and client.cursor == 1);
    frame.reactions[1].payload.clip.selection.clip = 5;
    frame.reactions[1].payload.clip.hit = std.mem.zeroes(p.SyncReactionHitOutcome);
    check(@src(), complete(&client, 1, 3, 8, 77, &actual) == 0 and r.reaction_journal_finish(&client) == 0);
    frame.reactions[1] = clip;
    frame.reactions[1].payload.clip.source_id = 0;
    frame.reactions[1].payload.clip.arena_attacker_slot = 2;
    frame.reactions[1].payload.clip.arena_attacker_generation = 9;
    frame.reactions[1].payload.clip.hit = std.mem.zeroes(p.SyncReactionHitOutcome);
    check(@src(), complete(&client, 1, 3, 8, 77, &actual) == 0 and complete(&client, 1, 3, 8, 0, &actual) == 0);
    frame.reactions[1] = clip;
    client.failed = 1;
    check(@src(), complete(&client, 1, 3, 8, 77, &actual) == 0);
    client.failed = 0;
    check(@src(), complete(&client, 2, 3, 8, 77, &actual) == 0);
    client.cursor = 1;
    frame.reactions[1] = clip;
    var wrong = actual;
    wrong.health_after = 2;
    check(@src(), complete(&client, 1, 3, 8, 77, &wrong) == -1 and client.cursor == 1 and client.failed == 11);
    client.failed = 0;
    wrong = actual;
    wrong.timer_before = 0.1;
    check(@src(), complete(&client, 1, 3, 8, 77, &wrong) == -1 and client.cursor == 1);
    client.failed = 0;
    wrong = actual;
    wrong.timer_after = std.math.nan(f32);
    check(@src(), complete(&client, 1, 3, 8, 77, &wrong) == -1 and client.cursor == 1);
    client.failed = 0;
    wrong = actual;
    wrong.life_after = 0;
    wrong.health_after = 0;
    wrong.action_after = 0;
    wrong.timer_after = 0;
    frame.reactions[1].payload.clip.hit = wrong;
    check(@src(), complete(&client, 1, 3, 8, 77, &wrong) == 1);
}
