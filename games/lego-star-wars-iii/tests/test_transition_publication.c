#undef NDEBUG
#include "../src/net/lan.c"
#include <assert.h>

int main(void) {
    generation=1;
    host_role=1;
    lan_publish_transition(1,6,1);
    assert(local_state.epoch==1 && local_state.level==6 && local_state.native_entry==1);
    lan_publish_transition(1,6,0);
    assert(local_state.native_entry==1);
    lan_publish_transition(2,7,0);
    assert(local_state.epoch==2 && local_state.level==7 && local_state.native_entry==0);
    lan_publish_transition(2,7,1);
    assert(local_state.native_entry==0);
    lan_publish_transition(3,8,2);
    assert(local_state.epoch==2 && local_state.level==7);

    struct PeerState remote={.epoch=2,.level=7,.native_entry=0};
    assert(session_peer(1,&remote));
    LanTransition accepted=lan_remote_transition();
    assert(accepted.epoch==2 && accepted.level==7 && accepted.native_entry==0);
    remote.epoch=3;remote.level=8;remote.native_entry=1;
    assert(session_peer(1,&remote));
    accepted=lan_remote_transition();
    assert(accepted.epoch==3 && accepted.level==8 && accepted.native_entry==1);
    remote.native_entry=2;
    assert(!session_peer(1,&remote));
    remote.native_entry=0;
    assert(!session_peer(2,&remote));
    accepted=lan_remote_transition();
    assert(accepted.epoch==3 && accepted.level==8 && accepted.native_entry==1);

    lan_publish_transition(4,12,1);
    remote=(struct PeerState){.epoch=3,.level=8,.ready=1};
    assert(session_peer(1,&remote));
    assert(!lan_peer_ready());
    remote.epoch=4;remote.level=12;remote.ready=0;
    assert(session_peer(1,&remote));
    assert(!lan_peer_ready());
    remote.ready=1;
    assert(session_peer(1,&remote));
    assert(lan_peer_ready());
    remote.ack=17;
    assert(session_peer(1,&remote));
    assert(lan_peer_ack()==17);
    remote.level=11;
    assert(session_peer(1,&remote));
    assert(lan_peer_ack()==0);
    remote.level=12;
    remote.ready=0;
    assert(session_peer(1,&remote));
    assert(!lan_peer_ready());
    remote.epoch=5;remote.level=13;remote.ready=1;
    assert(session_peer(1,&remote));
    assert(!lan_peer_ready());
    assert(lan_peer_ack()==0);
    status=LAN_CONNECTED;host_role=1;
    lan_publish_transition(6,7,0);
    SyncPreloadInput source={.epoch=6,.level=7,.serial=1,.root_phase=0xd,.clock=0,.rng_game=0xffffffff,.rng_engine=0xffffffff,.delta=.1f,.engine_delta=.1f};
    SyncWorldReady ready={6,7,0xd,0}, remote_ready={.level=-1};
    assert(!lan_publish_preload(&source));
    assert(lan_publish_world_ready(&ready));
    assert(!lan_publish_preload(&source));
    peer_state=(struct PeerState){.epoch=6,.level=7,.preload={.level=-1},.world_ready=ready};
    assert(lan_remote_world_ready(6,7,&remote_ready)&&preload_world_ready_matches(&ready,&remote_ready));
    assert(lan_publish_preload(&source));
    SyncPreloadReceipt receipt={1,2,0xe}, observed={0};
    assert(lan_publish_preload_receipt(6,7,&receipt));
    assert(!lan_publish_preload_seal(6,7,1));
    peer_state=(struct PeerState){.epoch=6,.level=7,.preload={.level=-1},.preload_receipt=receipt,.world_ready=ready};
    assert(lan_remote_preload_receipt(6,7,&observed));
    assert(observed.serial==1&&observed.world_calls==2);
    assert(!lan_publish_preload_seal(6,7,1));
    ready.root_phase=0xe;ready.completed_serial=1;assert(lan_publish_world_ready(&ready));
    assert(!lan_publish_preload_seal(6,7,1));peer_state.world_ready=ready;
    assert(lan_publish_preload_seal(6,7,1));
    assert(local_state.preload_seal==1);
    lan_publish_transition(7,7,0);
    assert(!local_state.preload.epoch&&!local_state.preload_receipt.serial&&!local_state.preload_seal);
    assert(!local_state.world_ready.epoch&&local_state.world_ready.level==-1);
    assert(!lan_publish_preload_receipt(6,7,&receipt));
    assert(!lan_remote_preload_receipt(7,7,&observed));
    host_role=0;
    peer_state=(struct PeerState){.epoch=7,.level=7,.preload=source,.preload_receipt=receipt,.preload_seal=1};
    peer_state.preload.epoch=7;
    ready=(SyncWorldReady){7,7,0xd,0};assert(lan_publish_world_ready(&ready));
    assert(lan_receive_preload(7,7,&source));
    assert(!lan_publish_preload(&source));
    assert(lan_publish_preload_receipt(7,7,&receipt));
    assert(lan_remote_preload_seal(7,7)==1);
    assert(lan_remote_preload_seal(6,7)==0);
    lan_publish_level(8);
    assert(!local_state.preload_receipt.serial&&!local_state.preload_seal);
    assert(!local_state.world_ready.epoch);
    ready=(SyncWorldReady){7,8,0xd,0};assert(lan_publish_world_ready(&ready));
    lan_invalidate_world_ready();assert(!local_state.world_ready.epoch&&local_state.world_ready.level==-1);
    ready.epoch=6;assert(!lan_publish_world_ready(&ready));
    ready.epoch=7;ready.level=7;assert(!lan_publish_world_ready(&ready));
    host_role=1;
    for(uint32_t phase=0xd;phase<=0xe;++phase){
        const uint32_t epoch=20+phase;
        lan_publish_transition(epoch,7,0);
        source=(SyncPreloadInput){.epoch=epoch,.level=7,.serial=1,.root_phase=phase,.delta=.1f,.engine_delta=.1f};
        ready=(SyncWorldReady){epoch,7,phase,0};
        peer_state=(struct PeerState){.epoch=epoch,.level=7,.world_ready=ready};
        assert(lan_publish_world_ready(&ready));assert(lan_publish_preload(&source));
        receipt=(SyncPreloadReceipt){1,1,phase};assert(lan_publish_preload_receipt(epoch,7,&receipt));
        ready.completed_serial=1;assert(lan_publish_world_ready(&ready));peer_state.world_ready=ready;
        assert(!lan_publish_preload_seal(epoch,7,1));
        peer_state.preload_receipt=receipt;
        peer_state.world_ready.root_phase=phase==0xd?0xe:0xd;
        assert(!lan_publish_preload_seal(epoch,7,1));peer_state.world_ready=ready;
        ++peer_state.preload_receipt.world_calls;
        assert(!lan_publish_preload_seal(epoch,7,1));peer_state.preload_receipt=receipt;
        peer_state.preload_receipt.end_phase=phase==0xd?0xe:0xd;
        assert(!lan_publish_preload_seal(epoch,7,1));peer_state.preload_receipt=receipt;
        assert(!local_state.preload_seal);
        assert(lan_publish_preload_seal(epoch,7,1));assert(local_state.preload_seal==1);
    }
    return 0;
}
